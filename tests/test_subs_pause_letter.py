def bounds(rows):
    return [{"text": t, "offset_sec": o, "duration_sec": d} for t, o, d in rows]


def starts(chunks, rows, lead_cut):
    return [round(x, 3) for x in subs.chunk_starts("".join(chunks), chunks, bounds(rows), lead_cut)]


